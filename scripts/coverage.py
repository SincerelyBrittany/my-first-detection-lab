"""Generate docs/coverage.md: which ATT&CK techniques the rules cover.

Run from the repo root:  python -m scripts.coverage
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from detectionlab.matcher import Rule, load_rules

ROOT = Path(__file__).resolve().parents[1]

# Techniques worth covering next, so the gaps are visible too.
PLANNED = {
    "T1110": "Brute force (failed logons, Event ID 4625)",
    "T1078.004": "Valid cloud accounts (console login without MFA)",
    "T1136.003": "New cloud account created (CreateUser + CreateLoginProfile)",
    "T1021.001": "Remote Desktop lateral movement",
    "T1047": "WMI execution",
    "T1070.001": "Windows event logs cleared",
}


def render(rules: list[Rule]) -> str:
    by_technique: dict[str, list[Rule]] = defaultdict(list)
    for rule in rules:
        for technique in rule.techniques:
            by_technique[technique].append(rule)

    lines = [
        "# Detection coverage",
        "",
        "Generated by `python -m scripts.coverage`; CI fails if this file is out of date.",
        "",
        "## Covered",
        "",
        "| ATT&CK technique | Rule | Log source | Level |",
        "| --- | --- | --- | --- |",
    ]
    for technique in sorted(by_technique):
        for rule in by_technique[technique]:
            source = rule.logsource.get("service") or rule.logsource.get("category", "")
            link = f"https://attack.mitre.org/techniques/{technique.replace('.', '/')}/"
            rel = rule.path.relative_to(ROOT).as_posix() if rule.path.is_absolute() else rule.path.as_posix()
            lines.append(f"| [{technique}]({link}) | [{rule.title}](../{rel}) | {source} | {rule.level} |")

    lines += ["", "## Not covered yet", "", "| ATT&CK technique | Idea |", "| --- | --- |"]
    for technique, idea in PLANNED.items():
        if technique not in by_technique:
            link = f"https://attack.mitre.org/techniques/{technique.replace('.', '/')}/"
            lines.append(f"| [{technique}]({link}) | {idea} |")
    lines += [
        "",
        f"{len(rules)} rules covering {len(by_technique)} techniques.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    out = ROOT / "docs" / "coverage.md"
    out.write_text(render(load_rules(ROOT / "rules")))
    print(f"wrote {out.relative_to(ROOT)}")
